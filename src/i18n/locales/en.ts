// Arabic has more plural forms than English (zero/one/two/few/many/other),
// so Arabic may add any of those variants of a key that takes a count.
type ExtraPluralForms = { [key: `${string}_${'zero' | 'one' | 'two' | 'few' | 'many' | 'other'}`]: string };
type Shape<T> = { [K in keyof T]: T[K] extends string ? string : Shape<T[K]> } & ExtraPluralForms;
export type Translations = Shape<typeof en>;

